export type DisplayDomain = keyof typeof DISPLAY_LABELS;
export function displayLabel(
  domain: DisplayDomain,
  value: string | null | undefined,
): string {
  if (value === null || value === undefined || value === "") return "未记录";
  const labels = DISPLAY_LABELS[domain] as Record<string, string>;
  return Object.prototype.hasOwnProperty.call(labels, value)
    ? labels[value]
    : "未识别值";
}

export function membershipLabel(level: number): string {
  return (
    ["普通用户", "白银会员", "黄金会员", "钻石会员", "超级会员"][level] ??
    `未识别会员等级（${level}）`
  );
}
